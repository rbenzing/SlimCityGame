describe('the family of a building by height', () => {
  it('draws every zoned home or business over the ceiling as glass, whatever its kind or level', () => {
    const modern = catalog.filter(isModernTall);
    expect(modern.length).toBeGreaterThan(20);
    for (const e of modern) {
      const params = deriveFacadeParams(e, 0);
      expect(params.family, `${e.id} (${e.kind} L${e.level}, ${e.height} m)`).toBe('glass');
      expect(params.windowInset, e.id).toBe(false);
    }
  });

  it('keeps every entry at or under the ceiling in the family it has always had', () => {
    const lower = catalog.filter((e) => e.height <= 19.2);
    const pinned = new Map<string, FacadeFamily>();
    for (const [family, ids] of Object.entries(FAMILY_AT_OR_UNDER_CEILING)) {
      for (const id of ids) pinned.set(id, family as FacadeFamily);
    }
    expect(pinned.size).toBe(lower.length);
    for (const e of lower) {
      expect(deriveFacadeParams(e, 0).family, e.id).toBe(pinned.get(e.id));
    }
  });

  it('keeps a tall civic building, utility or works in its own family', () => {
    const tall = catalog.filter((e) => e.height > 19.2 && !isModernTall(e));
    expect(tall.map((e) => e.id)).toContain('hospital');
    for (const e of tall) expect(deriveFacadeParams(e, 0).family, e.id).toBe('concrete');
    const works = catalog.find((e) => e.category === 'ind')!;
    expect(deriveFacadeParams({ ...works, height: 60 }, 0).family).toBe('concrete');
  });
});
